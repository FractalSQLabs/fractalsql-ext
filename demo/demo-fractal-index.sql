-- demo/demo-fractal-index.sql -- the native IVF index end to end.
--
-- Run:
--   { echo "LOAD '/path/to/fractalsql.capi.<platform>.duckdb_extension';"; cat demo/demo-fractal-index.sql; } \
--       | duckdb -unsigned
--
-- Safe to re-run: the demo tables are dropped and recreated each time.
--
-- What it shows:
--   1. the index is built (and the build streams -- the corpus is never held in memory);
--   2. the indexed search returns the SAME columns as the exact scan, and the same distances;
--   3. the index was ACTUALLY used (the rows it read are far fewer than the table holds);
--   4. the exact fallback: the same query with "use_index": false;
--   5. the delta: a row committed after the build is found by the indexed search, and
--      fractal_index_info reports the index as stale;
--   6. the candidates Scout would consume;
--   7. the index is dropped.
--
-- NOTE: the indexed search does NOT apply Diversify repulsion -- the nearest neighbours are
-- returned as they are. Use fractal_search_explore (Scout) when you want a diverse population.

.print === 0. Sanity check: extension loaded? ===
SELECT fractal_edition(), fractal_version();

.print
.print === 1. A small corpus: 3000 vectors, 8 dimensions, three clusters ===

DROP TABLE IF EXISTS fidx_demo;
CREATE TABLE fidx_demo (
    id    INTEGER PRIMARY KEY,
    label VARCHAR,
    v     DOUBLE[]
);

-- The vectors are generated by the database itself (deterministic, no random()): a "cluster" is
-- a small offset of a fixed centre, so the nearest neighbours of a centre are that cluster.
INSERT INTO fidx_demo
SELECT i,
       'c' || (i % 3),
       [0.5 + ((i % 100) - 50) / 10000.0,
        0.25 + ((i % 71) - 35) / 10000.0,
        0.75 + ((i % 37) - 18) / 10000.0,
        0.125 + ((i % 53) - 26) / 10000.0,
        0.375 + ((i % 29) - 14) / 10000.0,
        0.625 + ((i % 43) - 21) / 10000.0,
        0.875 + ((i % 61) - 30) / 10000.0,
        0.0 + ((i % 17) - 8) / 10000.0]
FROM range(1, 3000) t(i);

SELECT count(*) AS rows, count(DISTINCT label) AS clusters FROM fidx_demo;

.print
.print === 2. Build the index ===
-- The build streams: one pass trains the cells, a second encodes every row into a staging table.
-- The recall calibration then picks the nprobe that reaches the target recall.
SELECT fractal_index_create('fidx_demo', 'v',
       '{"name":"fidx_demo_v","vector_format":"FP32","nlist":16,"target_recall":0.95}') AS built;

.print
.print === 3. What the index knows about itself ===
SELECT (fractal_index_info('fidx_demo_v')::JSON->>'$.format')            AS format,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.dim')               AS dim,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.rows_indexed')      AS rows_indexed,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.nlist')             AS nlist,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.nprobe_default')    AS nprobe_default,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.has_delta')         AS has_delta,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.stale')             AS stale;

.print The verdict: status is ready / stale / degraded / empty / orphaned, and advice says what to do about it (nothing yet):
SELECT (fractal_index_info('fidx_demo_v')::JSON->>'$.status') AS status, (fractal_index_info('fidx_demo_v')::JSON->'$.advice') AS advice;
.print The catalog, one row per index:
SELECT name, table_name, vector_col, format, rows, status, generation FROM fractal_index_list();

.print
.print === 4. The indexed search (the same columns as fractal_search_telemetry) ===
SELECT * FROM fractal_search('fidx_demo', 'v', [0.5, 0.25, 0.75, 0.125, 0.375, 0.625, 0.875, 0.0]::DOUBLE[], 5, '{}');

.print
.print === 5. The exact scan, for comparison ===
SELECT * FROM fractal_search_telemetry('fidx_demo', 'v', [0.5, 0.25, 0.75, 0.125, 0.375, 0.625, 0.875, 0.0]::DOUBLE[], 5);

.print
.print === 6. The distances are EXACT (the index never returns an approximate distance) ===
-- Every row the index returned is compared with the cosine recomputed from the base table: the
-- two distances must be bit-identical, because every candidate is verified before it is returned.
-- (The index may return a DIFFERENT SET of neighbours than the exact scan -- that is what
-- approximate means -- but the distance it reports for a row is the exact one.)
WITH indexed AS (
    SELECT doc_id::BIGINT AS id, distance FROM fractal_search('fidx_demo', 'v', [0.5, 0.25, 0.75, 0.125, 0.375, 0.625, 0.875, 0.0]::DOUBLE[], 5, '{}')
), q AS (
    SELECT [0.5, 0.25, 0.75, 0.125, 0.375, 0.625, 0.875, 0.0]::DOUBLE[] AS v
)
SELECT i.id,
       i.distance AS indexed_distance,
       e.distance AS recomputed_distance,
       abs(i.distance - e.distance) < 1e-12 AS agrees
FROM indexed i
JOIN fidx_demo f ON f.id = i.id
CROSS JOIN q
CROSS JOIN LATERAL (
    SELECT 1.0
         - (SELECT sum(a * b) FROM (SELECT unnest(f.v) AS a, unnest(q.v) AS b))
           / sqrt((SELECT sum(a * a) FROM unnest(f.v) t(a)))
           / sqrt((SELECT sum(b * b) FROM unnest(q.v) u(b))) AS distance
) e;

.print
.print === 7. The index was ACTUALLY used (not a flat scan in disguise) ===
-- last_search.rows_scanned is what the index read -- the table holds 2999 rows.
SELECT (fractal_index_info('fidx_demo_v')::JSON->>'$.last_search.used_index')    AS used_index,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.last_search.rows_scanned') AS rows_scanned,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.last_search.cells_probed') AS cells_probed,
       (SELECT count(*) FROM fidx_demo)                                        AS table_rows;

.print
.print === 8. The exact fallback: the same query with use_index = false ===
SELECT * FROM fractal_search('fidx_demo', 'v', [0.5, 0.25, 0.75, 0.125, 0.375, 0.625, 0.875, 0.0]::DOUBLE[], 3, '{"use_index":false}');

.print
.print === 9. The delta: a row committed AFTER the build ===
-- The nested queries run in their own autocommit frame, so only COMMITTED rows are seen.
INSERT INTO fidx_demo VALUES (999999, 'new', [0.5, 0.25, 0.75, 0.125, 0.375, 0.625, 0.875, 0.0]);
INSERT INTO fidx_demo SELECT 1000000 + id, 'late copy', v FROM fidx_demo WHERE id BETWEEN 100 AND 199;

SELECT * FROM fractal_search('fidx_demo', 'v', [0.5, 0.25, 0.75, 0.125, 0.375, 0.625, 0.875, 0.0]::DOUBLE[], 3, '{}');

.print
.print === 10. The index knows it is stale now ===
SELECT (fractal_index_info('fidx_demo_v')::JSON->>'$.has_delta')         AS has_delta,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.stale')             AS stale,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.rows_indexed')      AS rows_indexed,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.rows_now')          AS rows_now;
.print The verdict says what changed and what to do (the added rows are scanned exactly on every search until you refresh):
SELECT (fractal_index_info('fidx_demo_v')::JSON->>'$.status')                 AS status,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.rows_added_since_build') AS added,
       (fractal_index_info('fidx_demo_v')::JSON->'$.advice')                  AS advice;

.print
.print === 11. The candidates Scout would consume ===
SELECT count(*) AS candidate_rows FROM fractal_index_candidates('fidx_demo', 'v', [0.5, 0.25, 0.75, 0.125, 0.375, 0.625, 0.875, 0.0]::DOUBLE[], '{"near":4,"per_cell":2}');

.print
.print === 12. Refresh: fold the added rows into the cells, with no retraining ===
SELECT (r::JSON->>'$.added') AS added, (r::JSON->>'$.rows') AS rows, (r::JSON->>'$.generation') AS generation
  FROM (SELECT fractal_index_refresh('fidx_demo_v') AS r);
SELECT (fractal_index_info('fidx_demo_v')::JSON->>'$.status')       AS status,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.has_delta')    AS has_delta,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.rows_indexed') AS rows_indexed,
       (fractal_index_info('fidx_demo_v')::JSON->'$.advice')        AS advice;
.print The late arrival is now served from the cells, not by the exact delta scan:
SELECT * FROM fractal_search('fidx_demo', 'v', [0.5, 0.25, 0.75, 0.125, 0.375, 0.625, 0.875, 0.0]::DOUBLE[], 3, '{}');

.print
.print === 13. Index plus filter in one call: the ids option ===
.print Pick the rows with ordinary SQL (here: the 'new' row and every row whose id ends in 7), pass their ids, and search only those.
.print (A DuckDB table function takes constant arguments, so the id list is spooled into a statement first -- the same .output/.read idiom the agent demos use.)
.mode list
.headers off
.output fidx_ids.sql
SELECT 'SELECT doc_id, round(distance, 6) AS distance FROM fractal_search(''fidx_demo'', ''v'', [0.5, 0.25, 0.75, 0.125, 0.375, 0.625, 0.875, 0.0]::DOUBLE[], 4, ''{"ids":'
       || (SELECT to_json(list(id))::VARCHAR FROM fidx_demo WHERE label = 'new' OR id % 10 = 7) || '}'');';
.output stdout
.mode box
.headers on
.read fidx_ids.sql
.print Every row returned is the 'new' row or ends in 7, so the filter held; the 'new' row is its own nearest neighbour.

.print
.print === 14. A rebuild picks the new row up ===
SELECT fractal_index_rebuild('fidx_demo_v') AS rebuilt;
SELECT (fractal_index_info('fidx_demo_v')::JSON->>'$.rows_indexed') AS rows_indexed,
       (fractal_index_info('fidx_demo_v')::JSON->>'$.stale')        AS stale;

.print
.print === 15. Drop it ===
SELECT fractal_index_drop('fidx_demo_v') AS dropped;

DROP TABLE IF EXISTS fidx_demo;
