"""Regenerates src/adapters/tools_spec.inc (the spec compiled into the server) from tools.spec.json.

tools.spec.json is the source of truth for the tool catalog: one entry per extension function with its
parameters, how each is bound, and how its result is returned. Run after editing it:

    python3 mcp/scripts/gen_spec_inc.py
"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
spec = json.load(open(os.path.join(here, "..", "tools.spec.json")))
text = json.dumps(spec, separators=(",", ":"))
# Split into chunks well under the compilers' string-literal limit, joined by adjacent-literal concatenation.
chunks = [text[i:i + 8000] for i in range(0, len(text), 8000)]
out = ["// SPDX-License-Identifier: Apache-2.0 AND BSD-2-Clause", "// Generated by scripts/gen_spec_inc.py from tools.spec.json. Do not edit.",
       "static const char* const kToolsSpecJson ="]
for c in chunks:
    out.append('R"FSQLSPEC(' + c + ')FSQLSPEC"')
out[-1] += ";"
open(os.path.join(here, "..", "src", "adapters", "tools_spec.inc"), "w").write("\n".join(out) + "\n")
print("wrote tools_spec.inc: %d tools, %d bytes" % (len(spec["tools"]), len(text)))
